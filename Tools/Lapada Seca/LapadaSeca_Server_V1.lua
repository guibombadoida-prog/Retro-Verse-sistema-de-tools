local ARQUETIPO = "MELEE"

local CFG = {
	RAIO_MAO        = 5.5,
	DANO            = 34,
	EMPURRAO        = 130,
	ALTURA          = 0.55,
	TEMPO_VOO       = 0.28,
	TOMBO           = 2.2,
	JANELA          = 0.35,
	PASSO           = 0.07,
	INTERVALO_ALVO  = 0.5,
	RECARGA         = 0.7,

	RECARGA_EXTRA   = 14,
	DURACAO_QUENTE  = 5,
	DANO_QUENTE     = 21,
	EMPURRAO_QUENTE = 165,
}

--═══════════════════════════════════════════════════════════════
-- ESTADO
